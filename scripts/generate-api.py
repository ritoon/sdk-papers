#!/usr/bin/env python3
"""Generate Go DTOs and operations from the pinned official Pappers contract.
Python standard library only. Run from repository root. Operations are enabled
in api/operations.json, in commit order; shared DTOs belong to their first user.
"""
import json
import re
from pathlib import Path

spec = json.loads(Path('api/pappers-2.20.0.json').read_text())
operations = json.loads(Path('api/operations.json').read_text())
known = set()

def name(value):
    value = value.replace('n-1', 'n_minus_1')
    return ''.join(x[:1].upper() + x[1:] for x in re.findall(r'[A-Za-z0-9]+', value))

def resolve(s):
    if '$ref' in s:
        v = spec
        for part in s['$ref'].split('/')[1:]:
            v = v[part]
        return resolve(v)
    if 'allOf' in s:
        props = {}
        for part in s['allOf']:
            props.update(resolve(part).get('properties', {}))
        props.update(s.get('properties', {}))
        return dict(s, type='object', properties=props)
    if 'oneOf' in s:
        assert all(x.get('type') == 'string' for x in s['oneOf'])
        return dict(s, type='string')
    return s

def typename(s, hint, defs):
    if '$ref' in s:
        n = name(s['$ref'].split('/')[-1])
        if n not in known:
            known.add(n)
            t = typename(resolve(s), n, defs)
            if t != n:
                defs.append(f'type {n} {t}\n')
        return n
    s = resolve(s)
    if 'properties' in s:
        n = hint
        fields = []
        for k, v in s['properties'].items():
            t = typename(v, n + name(k), defs)
            if public == 'SuggestionsWithOptions' and k == 'entreprise_cessee':
                t = 'Boolean01'
            if not t.startswith(('[]', 'map[')):
                t = '*' + t
            fields.append(f'\t{name(k)} {t} `json:"{k},omitempty"`')
        defs.append(f'type {n} struct {{\n' + '\n'.join(fields) + '\n}\n')
        return n
    t = s.get('type')
    if t == 'array':
        return '[]' + typename(s.get('items', {}), hint + 'Item', defs)
    if t == 'object':
        if isinstance(s.get('additionalProperties'), dict):
            return 'map[string]' + typename(s['additionalProperties'], hint + 'Value', defs)
        return 'map[string]json.RawMessage'
    return {'string': 'string', 'boolean': 'bool', 'integer': 'int64', 'number': 'float64'}.get(t, 'json.RawMessage')

for entry in operations:
    method, path, public = entry
    webhook = method == 'WEBHOOK'
    op = spec['webhooks'][path]['post'] if webhook else spec['paths'][path][method.lower()]
    defs = []
    code = ''
    if webhook:
        schema = op['requestBody']['content']['application/json']['schema']
        typ = typename(schema, public, defs)
        event = {'webhook_entreprise':'notifications.entreprises','webhook_dirigeant':'notifications.dirigeants','veille_evenement':'notifications.veille'}[path]
        code += f'// Decode{public} décode {path}. Le décodage ne vérifie pas l’origine du webhook.\n'
        code += f'func Decode{public}(data []byte) (*{typ}, error) {{\n return decodeWebhook[{typ}](data, "{event}")\n}}\n'
    else:
        params = []
        for p in op.get('parameters', []):
            p = resolve(p)
            assert p['in'] == 'query'
            t = typename(p['schema'], public + name(p['name']), defs)
            assert t in ('string', 'bool', 'int64', 'float64')
            tag = ',required' if p.get('required') else ''
            params.append(f' {name(p["name"])} *{t} `query:"{p["name"]}{tag}"`')
        defs.append(f'type {public}Params struct {{\n' + '\n'.join(params) + '\n}\n')
        body = 'nil'
        args = f'ctx context.Context, params {public}Params'
        if 'requestBody' in op:
            typ = typename(op['requestBody']['content']['application/json']['schema'], public + 'Body', defs)
            args += ', body ' + typ
            body = 'body'
        statuses = [str(k) for k in op['responses'] if str(k).startswith('2')]
        contents = op['responses'][statuses[0]].get('content', {})
        kind = 'responseJSON'
        if 'application/json' in contents:
            typ = typename(contents['application/json']['schema'], public + 'Result', defs)
        elif contents:
            typ, kind = '[]byte', 'responseBinary'
        else:
            typ, kind = 'struct{}', 'responseEmpty'
        code += f'// {public} : {op.get("summary", "").replace(chr(10), " ")}\n'
        code += f'// {method} {path} — Pappers 2.20.0. Les options payantes sont explicites.\n'
        code += f'func (c *Client) {public}({args}) (*Response[{typ}], error) {{\n'
        code += f' return callAPI[{typ}](c, ctx, "{method}", "{path}", params, {body}, {kind}, []int{{{", ".join(statuses)}}})\n}}\n'
    source = '\n'.join(defs) + '\n' + code
    imports = []
    if not webhook: imports.append('"context"')
    if 'json.RawMessage' in source: imports.append('"encoding/json"')
    header = '// Code generated by scripts/generate-api.py from Pappers 2.20.0; DO NOT EDIT.\npackage papers\n'
    if imports: header += 'import (' + ';'.join(imports) + ')\n'
    Path('api_' + public.lower() + '.go').write_text(header + source)

# Contract fixtures deliberately use synthetic values, never upstream examples.
def fixture(s, depth=0):
    s = resolve(s)
    if depth > 5:
        return None
    if 'properties' in s:
        return {k: value for k, v in s['properties'].items()
                if (value := fixture(v, depth + 1)) is not None}
    if s.get('type') == 'array':
        v = fixture(s.get('items', {}), depth + 1)
        return [v] if v is not None else None
    if s.get('type') == 'object':
        if isinstance(s.get('additionalProperties'), dict):
            return {'2025': fixture(s['additionalProperties'], depth + 1)}
        return {'synthetic': True}
    if s.get('enum'):
        return s['enum'][0]
    return {'string': 'fixture & é', 'boolean': True, 'integer': 2, 'number': 2.5}.get(s.get('type'), 'fixture')

for method, path, public in operations:
    if method == 'WEBHOOK':
        continue
    op = spec['paths'][path][method.lower()]
    params, query = [], []
    for p in op.get('parameters', []):
        p = resolve(p)
        typ = p['schema']['type']
        val = {'string': '"fixture & é"', 'boolean': 'false', 'integer': 'int64(2)', 'number': 'float64(2.5)'}[typ]
        want = {'string': 'fixture & é', 'boolean': 'false', 'integer': '2', 'number': '2.5'}[typ]
        params.append(f'{name(p["name"])}: Pointer({val})')
        query.append(f'"{p["name"]}": {{"{want}"}}')
    statuses = [str(k) for k in op['responses'] if str(k).startswith('2')]
    contents = op['responses'][statuses[0]].get('content', {})
    raw = json.dumps(fixture(contents['application/json']['schema']), ensure_ascii=False) if 'application/json' in contents else ('%PDF-synthetic' if contents else '')
    bodyarg, bodycode, expectedbody = '', '', '""'
    if 'requestBody' in op:
        # Reuse generated argument type, including named array items.
        text = Path('api_' + public.lower() + '.go').read_text()
        bodytype = re.search(r'params '+public+r'Params, body (.+?)\)', text).group(1)
        bodyraw = json.dumps(fixture(op['requestBody']['content']['application/json']['schema']), ensure_ascii=False)
        bodycode = f'var body {bodytype}\nrequire.NoError(t, json.Unmarshal([]byte(`{bodyraw}`), &body))\n'
        bodyarg, expectedbody = ', body', '`' + bodyraw + '`'
    test = f'''// Code generated by scripts/generate-api.py; DO NOT EDIT.
package papers
import ("context"; "net/http"; "net/url"; "testing"; "io"; "encoding/json"; "github.com/stretchr/testify/require")
func Test{public}Contract(t *testing.T) {{
 {bodycode}
 for _, status := range []int{{{', '.join(statuses)}, 401}} {{
  calls := 0
  c := New("fixture-token", WithDoer(func(_ *http.Client, r *http.Request) (*http.Response, error) {{
   calls++
   require.Equal(t, "{method}", r.Method)
   require.Equal(t, "/v2{path}", r.URL.Path)
   require.Equal(t, url.Values{{{', '.join(query)}}}, r.URL.Query())
   require.Equal(t, "fixture-token", r.Header.Get("api-key"))
   require.NotContains(t, r.URL.String(), "fixture-token")
   payload, err := io.ReadAll(r.Body); require.NoError(t, err)
   if {expectedbody} != "" {{ require.JSONEq(t, {expectedbody}, string(payload)); require.Equal(t, "application/json", r.Header.Get("Content-Type")) }} else {{ require.Empty(t, payload) }}
   res := response(status, `{raw}`)
   res.Header.Set("X-Test", "fixture")
   return res, nil
  }}))
  result, err := c.{public}(context.Background(), {public}Params{{{', '.join(params)}}}{bodyarg})
  require.Equal(t, 1, calls)
  if status == 401 {{ var apiErr *APIError; require.ErrorAs(t, err, &apiErr); require.Nil(t, result); continue }}
  require.NoError(t, err)
  require.Equal(t, status, result.StatusCode)
  require.Equal(t, "fixture", result.Header["X-Test"][0])
  require.Equal(t, `{raw}`, string(result.RawBody))
'''
    if 'application/json' in contents:
        test += f'encoded, err := json.Marshal(result.Body); require.NoError(t, err); require.JSONEq(t, `{raw}`, string(encoded))\n'
    else:
        test += '_ = json.Valid\n'
        if contents: test += f'require.Equal(t, []byte(`{raw}`), result.Body)\n'
    test += ' }\n}\n'
    Path('api_' + public.lower() + '_test.go').write_text(test)
